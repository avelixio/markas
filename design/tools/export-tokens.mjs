// Writes the design tokens and the icon set into the web UI, so the design sources stay the
// single place where a colour or an icon is defined.
//
//   node design/tools/export-tokens.mjs
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { ICONS } from "../src/icons.mjs";
import { COLORS, RADIUS, SPACE } from "../src/tokens.mjs";

const out = (file) => fileURLToPath(new URL(`../../src/renderer/src/ui/${file}`, import.meta.url));
const cssName = (name) => `--mk-${name.replaceAll("/", "-")}`;

const block = (index) =>
  Object.entries(COLORS)
    .map(([name, values]) => `  ${cssName(name)}: ${values[index].toLowerCase()};`)
    .join("\n");

const css = `/* Generated by design/tools/export-tokens.mjs from design/src/tokens.mjs. Do not edit. */
:root {
  color-scheme: dark;
${block(0)}
${Object.entries(SPACE)
  .map(([step, px]) => `  --mk-space-${step}: ${px}px;`)
  .join("\n")}
${Object.entries(RADIUS)
  .map(([name, px]) => `  --mk-radius-${name}: ${px}px;`)
  .join("\n")}
  --mk-font-ui: "Inter Variable", "Inter", system-ui, -apple-system, "Segoe UI", sans-serif;
  --mk-font-mono: ui-monospace, "SF Mono", "Cascadia Mono", Consolas, "Liberation Mono", monospace;
}

:root[data-theme="light"] {
  color-scheme: light;
${block(1)}
}
`;

const icons = `// Generated by design/tools/export-tokens.mjs from design/src/icons.mjs. Do not edit.
// Each icon is drawn on a 16 unit grid: a string is SVG path data, [cx, cy, r] is a circle.
export const ICONS = ${JSON.stringify(ICONS, null, 2)} as const satisfies Record<
  string,
  ReadonlyArray<string | readonly [number, number, number]>
>;

export type IconName = keyof typeof ICONS;
`;

await writeFile(out("tokens.css"), css, "utf8");
await writeFile(out("icons.ts"), icons, "utf8");
console.log("wrote ui/tokens.css and ui/icons.ts");
