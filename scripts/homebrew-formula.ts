// Writes Formula/markas.rb for one release, from that release's SHA-256 lists.
//
//   bun scripts/homebrew-formula.ts 0.1.0 <folder with SHA256SUMS-*.txt>
//
// The formula installs the `markas` command, not the desktop app: Homebrew downloads it with
// curl, so the program runs like any other command-line tool installed with Homebrew.
// People install it with:
//
//   brew tap avelixio/markas https://github.com/avelixio/markas
//   brew install avelixio/markas/markas
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const REPO = "avelixio/markas";
const TARGETS = { "macos-arm64": "", "macos-x64": "", "linux-x64": "" };

const [version, sumsFolder] = process.argv.slice(2);
if (!version || !/^\d+\.\d+\.\d+$/.test(version) || !sumsFolder) {
  throw new Error(
    "Usage: bun scripts/homebrew-formula.ts <version> <folder with SHA256SUMS-*.txt>",
  );
}

const sums: Record<string, string> = { ...TARGETS };
for (const target of Object.keys(TARGETS)) {
  const list = await readFile(join(sumsFolder, `SHA256SUMS-${target}.txt`), "utf8");
  const file = `markas-${version}-${target}.zip`;
  const line = list
    .split(/\r?\n/)
    .map((entry) => entry.trim().split(/\s+/))
    .find(([, name]) => name === file);
  if (!line || !/^[0-9a-f]{64}$/.test(line[0] ?? "")) {
    throw new Error(`SHA256SUMS-${target}.txt does not name ${file}.`);
  }
  sums[target] = line[0] as string;
}

const url = (target: string) =>
  `https://github.com/${REPO}/releases/download/v${version}/markas-${version}-${target}.zip`;

const formula = `# Generated by scripts/homebrew-formula.ts for Markas ${version}. Do not edit by hand.
class Markas < Formula
  desc "Headquarters for your AI bots, run from your own computer"
  homepage "https://github.com/${REPO}"
  version "${version}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${url("macos-arm64")}"
      sha256 "${sums["macos-arm64"]}"
    end
    on_intel do
      url "${url("macos-x64")}"
      sha256 "${sums["macos-x64"]}"
    end
  end

  on_linux do
    on_intel do
      url "${url("linux-x64")}"
      sha256 "${sums["linux-x64"]}"
    end
  end

  def install
    # The program finds its web interface and ready-made bots beside itself, so the folder stays whole.
    libexec.install Dir["*"]
    bin.write_exec_script libexec/"markas"
  end

  def caveats
    <<~EOS
      Run \`markas\` to start Markas. It opens in your browser.
      Bots need Claude Code, Codex or OpenCode, which Markas can find and connect from its Switchboard.
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/markas --version")
  end
end
`;

await writeFile(join(import.meta.dir, "..", "Formula", "markas.rb"), formula);
console.log(`Wrote Formula/markas.rb for ${version}.`);
